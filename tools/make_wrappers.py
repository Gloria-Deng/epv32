#!/usr/bin/env python3
"""从 rtl/epv32_core.v 的端口表生成 rtl/synth_wrappers.v (两个面积档)。

为什么要有这个生成器而不是手写 wrapper: 核的端口一旦增删, 手写的封装就会悄悄
少连一个端口, 而 `opt` 会把没人读的逻辑当死代码删掉, 综合仍退 0 并给出一张
近乎空白的统计表 (本机实测过一次: 2 wires / 0 cells)。生成器把端口表当唯一
真源, 并强制所有输出被 probe 读掉, 让「统计为空」不可能伪装成成功。
"""
import io, re, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src  = os.path.join(ROOT, "rtl", "epv32_core.v")
dst  = os.path.join(ROOT, "rtl", "synth_wrappers.v")

s = io.open(src, encoding="utf-8").read()
m = re.search(r'module epv32_core #\(.*?\)\((.*?)\);', s, re.S)
assert m, "epv32_core port list not found"
body = re.sub(r'[ \t]*//[^\n]*', '', m.group(1))
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
ins, outs = [], []
for c in body.split(','):
    c = ' '.join(c.split())
    if not c:
        continue
    mm = re.match(r'(input|output)\s+(?:wire\s+|reg\s+)?(?:signed\s+)?'
                  r'(\[[^\]]*\]\s*)?([A-Za-z_]\w*)$', c)
    assert mm, "unparsed port decl: " + c
    d, w, p = mm.groups()
    w = (w or '').strip()
    (outs if d == 'output' else ins).append((p, w))
assert len(ins) >= 4 and len(outs) >= 10, "port parse looks wrong: %r" % ((len(ins), len(outs)),)

L = ["// Generated by tools/make_wrappers.py -- DO NOT EDIT BY HAND.",
     "//",
     "// Synthesis-only thin wrappers: EPV_ENABLE is pinned at instantiation so",
     "// the two area arms are separate, unambiguous tops.  The delivered",
     "// simulation/SoC top is still epv32_soc.",
     "//",
     "// Why `probe` exists: an earlier version left every core output dangling",
     "// on an unused wire; `opt` deleted the whole core as dead code and printed",
     "// 2 wires / 0 cells -- while the script still exited 0.  XOR-ing every",
     "// output into a real port gives each bit a load, so an empty stat cannot",
     "// masquerade as success."]
for name, en in (("epv32_core_epv", 1), ("epv32_core_noepv", 0)):
    L += ["", "module %s (" % name]
    L += ["  input  wire %s%s," % ('%-8s' % w if w else ' ' * 8, p) for p, w in ins]
    L += ["  output wire %s%s," % ('%-8s' % w if w else ' ' * 8, p) for p, w in outs]
    L += ["  output wire probe", ");", "",
          "  epv32_core #(.EPV_ENABLE(%d)) dut (" % en]
    L += ["    .%s(%s)%s" % (p, p, "," if i < len(ins + outs) - 1 else "")
          for i, (p, _) in enumerate(ins + outs)]
    L += ["  );", "",
          "  assign probe = ^{ %s };" % ", ".join(p for p, _ in outs),
          "", "endmodule"]
io.open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote %s  ins=%d outs=%d" % (os.path.relpath(dst, ROOT), len(ins), len(outs)))
